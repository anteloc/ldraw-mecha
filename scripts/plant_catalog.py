def fmt(v):
    return f"{v:.3g}"


def recipe_text(r):
    if r["kind"] == "osc":
        drive = (f"drag · swing ({fmt(r['swing'][0])}, {fmt(r['swing'][1])})" if r["drive"] == "drag"
                 else f"asym {fmt(r['asym'])}" + (f" + {fmt(r['asym_v'])}·v" if r["asym_v"] else ""))
        extra = []
        if r.get("lift"):
            extra.append(f"lift {fmt(r['lift'])}")
        if r["lag"]:
            extra.append(f"lag {fmt(r['lag'])} f")
        if r["threshold"]:
            extra.append(f"threshold {fmt(r['threshold'])}")
        if r["flutter"]:
            extra.append("flutter " + ", ".join(f"{fmt(a)}@{fmt(f)} Hz" for a, f, _ in r["flutter"]))
        return (f"osc {fmt(r['f'])} Hz, ζ {fmt(r['zeta'])}, gain {fmt(r['gain'])}, {drive}"
                + (f"; {'; '.join(extra)}" if extra else ""))
    if r["kind"] == "spin":
        return (f"spin k {fmt(r['k'])}, u0 {fmt(r['u0'])}, damping {fmt(r['damping'])}/f, "
                f"{r['steps']} steps of 2π/{r['symmetry']} per breeze period")
    return (f"vane K {fmt(r['stiffness'])}, c {fmt(r['damping'])}, rest heading {fmt(math.degrees(r['heading']))}°"
            + (", flutter" if r["flutter"] else ""))


def clearance_summary():
    path = wc.OUT / "clearance-summary.json"
    return json.loads(path.read_text())["cases"] if path.exists() else {}


def peak(doc, ch):
    return max(abs(v) for v in doc["baked"][ch])


def markdown(docs, clearance):
    by_case = {}
    for d in docs:
        by_case.setdefault(d["case"], []).append(d)
    L = [
        "# Plant wind catalog",
        "",
        "Twenty LEGO plant cases moved by one shared wind, three wind clips each, in one scene of one file: "
        "[`plants.blend`](plants.blend) (scene **Wind**). Generated by `scripts/build_plants.py catalog` from "
        "`scripts/wind_clips.py`. See [`REPORT.md`](REPORT.md) for how the cases were built and checked.",
        "",
        "## How to find a how-to",
        "",
        "1. Pick a case by plant (table below) or a motion style (style index), or a joint kind (real LEGO freedom "
        "or `flex_approx`).",
        "2. In `plants.blend` open the collection `Pxx_key Title` (outliner: *Plant wind catalog*). It holds the "
        "model, its rig, the controller `CTRL_plant_xx_*` with the three NLA tracks, the floor labels and the camera "
        "`CAM_Pxx`; set `CAM_Pxx` as the active camera to see that case alone, or keep `CAM_Overview` for the field.",
        "3. Reuse the clip's Action (Blender), its JSON values (`clips/<case>.<regime>.json`), or regenerate it with "
        "the same response recipe for a new model (see *Reusing a wind response*).",
        "",
        f"Timeline (24 fps): **A breeze** frames {wc.WINDOWS['A'][0]}–{wc.WINDOWS['A'][1]}, **B gusty** "
        f"{wc.WINDOWS['B'][0]}–{wc.WINDOWS['B'][1]}, **C storm** {wc.WINDOWS['C'][0]}–{wc.WINDOWS['C'][1]} "
        "(markers of the same names). Every clip starts and ends at rest (spins on a symmetric step); between windows "
        f"each plant holds its rest pose. Breeze clips loop seamlessly over clip frames {wc.LOOP[0]}–{wc.LOOP[1]} "
        f"(timeline {wc.LOOP[0]}–{wc.LOOP[1]}).",
        "",
        "## The wind",
        "",
        "One wind blows toward **+X** (left to right in the overview, LDraw and Blender X). Its speed U and "
        "cross component V are normalised (storm gusts reach about 1.1). Gusts and turbulence are frozen into the "
        f"air and travel along +X at {wc.GUST_SPEED:g} LDU per frame from x = {wc.X0:g} LDU, so a case in column c "
        "feels every gust later than the column to its left:",
        "",
        "| Column | Slot x (LDU) | Delay (frames) | Cases |",
        "| --- | --- | --- | --- |",
    ]
    for col in range(wc.COLUMNS):
        x, _ = wc.slot_xz(0, col)
        names = ", ".join(c["key"][:3] for c in wc.CASES if c["slot"][1] == col)
        L.append(f"| {col + 1} | {x:g} | {wc.delay(x):.1f} | {names} |")
    L += [
        "",
        "| Regime | Mean U | Gusts (clip frame: extra U) | Turbulence / cross wind | Envelope |",
        "| --- | --- | --- | --- | --- |",
    ]
    for w in "ABC":
        s = wc.REGIME_SPECS[w]
        gusts = ", ".join(f"{c:g}: +{a:g}" for c, a, _ in s["gusts"]) or "— (periodic swell, 96-frame period)"
        ramp = "constant (clip faded in/out over 24 frames)" if s["ramp"] is None else (
            f"rises over frames {s['ramp'][0]}–{s['ramp'][1]}, dies over {s['ramp'][2]}–{s['ramp'][3]}")
        L.append(f"| {w} {wc.REGIMES[w]} | {s['mean']:g} | {gusts} | ±{sum(a for a, _, _ in s['turb']):.2f} / "
                 f"±{sum(a for a, _, _ in s['cross']):.2f} | {ramp} |")
    L += [
        "",
        "The **WIND** object (collection *Wind*) carries the same field at x = 0 as custom properties `speed`, `u`, "
        "`v` on its own NLA tracks (Actions `WIND.breeze`, `WIND.gusty`, `WIND.storm`) and drives the length of the "
        "blue arrow. It is a reference signal: the plant clips were computed from the field directly.",
        "",
        "## Cases",
        "",
        "Sign conventions: lean/bend/swing joints **+ = downwind (+X)**; hinged leaves and fronds **+ = tip rises**; "
        "twist/spin/vane joints turn right-handed about the stated axis. `real` = the LEGO connection allows that "
        f"rotation; `flex_approx` = a rigid-part tilt standing in for bending plastic (≤ {wc.FLEX_LIMIT} rad).",
        "",
        "| Case (collection) | Plant → mount | Motion | Styles | Joints (real / flex_approx) |",
        "| --- | --- | --- | --- | --- |",
    ]
    for c in wc.CASES:
        real = sum(1 for s in c["controls"].values() if s["joint"] == "real")
        flex = len(c["controls"]) - real
        L.append(f"| **{c['key']}** {c['title']} | {c['element']} | {c['how']} | "
                 f"{', '.join(f'`{s}`' for s in c['styles'])} | {real} / {flex} |")
    L += ["", "## Controls and response recipes", ""]
    for c in wc.CASES:
        plan = contract.load(wc.OUT / c["key"] / "plan.json")
        bodies = {b["signal"].rsplit("_", 1)[0] if b["signal"].endswith(("_angle", "_offset")) else b["signal"]: (n, b)
                  for n, b in plan["bodies"].items()}
        L += [f"### {c['key']} {c['title']}", "",
              f"Controller `CTRL_{c['plan']}`, camera `CAM_{c['key'][:3]}`, slot {wc.case_slot(c)} LDU.", "",
              "| Control | Range (rad) | Joint | + meaning | Axis / origin (case LDU) | Recipe |",
              "| --- | --- | --- | --- | --- | --- |"]
        for name, spec in c["controls"].items():
            body = bodies.get(name)
            frame = (f"{body[1]['axis']} @ {body[1]['origin']}" + (f" (parent {body[1]['parent']})"
                                                                  if body[1].get("parent") else "")) if body else "—"
            L.append(f"| `{name}` | {fmt(spec['min'])}…{fmt(spec['max'])} | {spec['joint']} | {spec['description']} "
                     f"| {frame} | {recipe_text(spec['recipe'])} |")
        L.append("")
    L += ["## Clips", "", "| Clip (Action) | NLA track | Styles | Loop | Peak |value| per channel (rad) |",
          "| --- | --- | --- | --- | --- |"]
    for d in docs:
        loop = f"{d['loop_range'][0]}–{d['loop_range'][1]}" if d["loop_range"] else "—"
        peaks = ", ".join(f"{ch} {peak(d, ch):.2f}" for ch in list(d["channels"])[:6])
        if len(d["channels"]) > 6:
            peaks += ", …"
        L.append(f"| `{d['id']}` | `{d['blender']['nla_track']}` | {', '.join(d['styles'])} | {loop} | {peaks} |")
    L += ["", "## Style index", "", "| Style | Meaning | Cases |", "| --- | --- | --- |"]
    for style, meaning in wc.STYLES.items():
        cases = [c["key"] for c in wc.CASES if style in c["styles"]]
        if style in ("breeze_loop", "gust_response", "storm_push"):
            cases = ["all (clip " + {"breeze_loop": "A", "gust_response": "B", "storm_push": "C"}[style] + ")"]
        L.append(f"| `{style}` | {meaning} | {', '.join(f'`{x}`' for x in cases) or '—'} |")
    L += [
        "",
        "## Joint kinds",
        "",
        "| Joint | LEGO connection | Cases |",
        "| --- | --- | --- |",
        "| Ball in socket (one of two tilts used, about Z) | 2536a palm segments; 22484 ball in 14418 friction socket "
        "| P01, P03, P10 |",
        "| Clip on bar (hinge about the bar) | 10884 / 30239 swordleaf clips on handles and frond bars; 2540 handles in "
        "61252 clips; 28870 / vine end bars in clips | P02, P05, P08, P11, P13, P16, P17 |",
        "| Bar or pin turning in a hole | bamboo leaf bricks and 1566 tiers on bars; 3742 / 32606 on flower pins; "
        "stems in vase studs; 30339 on an axle; leaves on a bar top | P01, P03, P04, P06, P09, P14, P15, P19, P20 |",
        "| Part turning on a stud | 2423 leaves on side studs, low plants on base studs | P12, P18 |",
        f"| flex_approx (tilt ≤ {wc.FLEX_LIMIT} rad standing in for bending) | none: thin stems, grass, the flexible "
        "vine, palm leaves on two prongs | P01, P04, P05, P07, P08, P09, P14 |",
        "",
        "## Clearance",
        "",
        "Sampled with `scripts/blender/check_plants_clearance.py`: every control swept alone, then every 4th frame of "
        "every clip; rest-contact pairs excluded; depth = deepest vertex of one part inside the other. Sampled "
        "evidence, not a proof of collision-free motion.",
        "",
        "| Case | Result | Pairs (worst vertex depth over the clips) |",
        "| --- | --- | --- |",
    ]
    for c in wc.CASES:
        v = clearance.get(c["key"])
        if not v:
            L.append(f"| {c['key']} | not run | — |")
            continue
        pairs = {}
        for clip, pp in v.get("vertex_penetration", {}).items():
            for pair, m in pp.items():
                pairs[pair] = max(pairs.get(pair, 0.0), m["max_vertex_depth_ldu"])
        text = ", ".join(f"{p} ({d:.2f} LDU)" for p, d in sorted(pairs.items(), key=lambda kv: -kv[1])[:6]) or "—"
        if len(pairs) > 6:
            text += f", … ({len(pairs)} pairs)"
        L.append(f"| {c['key']} | {v.get('worst_kind', '?')} | {text} |")
    L += [
        "",
        "## Reusing a wind response",
        "",
        "- **Data only:** `clips/<case>.<regime>.json` holds one value per frame (`baked`), each channel's unit, "
        "range, meaning, joint kind, response recipe and wind delay. `clips/WIND.json` holds the shared wind.",
        "- **Blender:** every clip is an Action with one slot (`plant_controller`) keyed on the controller's custom "
        "properties (`[\"bend_1\"]`, `[\"frond_upwind\"]` …), one LINEAR key per frame. It plays on any controller "
        "with the same property names and meanings:",
        "",
        "```python",
        "import bpy",
        "src = '/abs/path/output/plants/plants.blend'",
        "with bpy.data.libraries.load(src, link=False) as (data_from, data_to):",
        "    data_to.actions = ['P02_swordleaf_palm.storm']",
        "action = data_to.actions[0]",
        "ctrl = bpy.data.objects['CTRL_plant_13_fern']  # any controller with frond_downwind / frond_upwind / ...",
        "ad = ctrl.animation_data_create()",
        "track = ad.nla_tracks.new()",
        "strip = track.strips.new(action.name, 1, action)",
        "strip.action_slot = action.slots[0]",
        "```",
        "",
        "- **Whole case:** append the collection `Pxx_key Title` (model, rig, controller with its NLA tracks, "
        "SLOT_ empty, camera); the Actions come along through the NLA strips.",
        "- **A new plant on another model:** rig the joint (same kind of connection; measure axis and origin), "
        "choose the + sign by the conventions above, then generate its clips from a recipe of the closest case. The "
        "recipe's `x` (joint x) and `swing` (horizontal motion of the tip per radian) must be remeasured on the new "
        "model; they decide how the shared wind direction acts on the joint:",
        "",
        "```python",
        "import sys; sys.path.insert(0, 'scripts')",
        "import wind_clips as wc",
        "spec = wc.control('radian', -0.3, 0.3, 'Branch on its clip; + lifts the tip',",
        "                  wc.osc(1.3, 0.05, 0.9, x=0.0, swing=(0.12, 0.0), lift=0.2))  # as P11 branch_bounce",
        "breeze = wc.respond(spec, 'A', slot_x=0.0)   # 240 values, loops over frames 25-217",
        "storm = wc.respond(spec, 'C', slot_x=0.0)",
        "```",
        "",
        "Recipes: `osc` (damped second-order response to drag; `lag` delays it, `lift` adds a rise in strong wind, "
        "`threshold` ignores weak wind, `flutter` adds fast sines growing with |W|²), `spin` (a rotor whose speed "
        "follows the wind), `vane` (turns toward the downwind heading). A chain (whip) uses one `osc` per joint "
        "with growing gain and lag toward the tip.",
    ]
    return "\n".join(L) + "\n"


def write(out=wc.OUT):
    docs = wc.export(out)
    clearance = clearance_summary()
    cases = []
    for c in wc.CASES:
        d = out / c["key"]
        info = json.loads((d / "source/parts.json").read_text())
        plan = contract.load(d / "plan.json")
        cases.append(dict(
            case=c["key"], title=c["title"], element=c["element"], how=c["how"], styles=c["styles"],
            plan=c["plan"], controller=f"CTRL_{c['plan']}", collection=f"{c['key']} {c['title']}",
            camera=f"CAM_{c['key'][:3]}", slot_ldu=list(wc.case_slot(c)),
            wind_delay_frames=round(wc.delay(wc.case_slot(c)[0]), 3),
            controls={k: {f: v for f, v in s.items()} for k, s in c["controls"].items()},
            parts=info["parts"], joints=info["joints"], reference_checks=info["reference_checks"],
            geometry_checks=info.get("geometry_checks", []),
            bodies={b: dict(kind=v["kind"], origin=v["origin"], axis=v["axis"], parent=v.get("parent"),
                            signal=v["signal"], instances=v["instances"]) for b, v in plan["bodies"].items()},
            clips=[d_["id"] for d_ in docs if d_["case"] == c["key"]],
            clearance=clearance.get(c["key"], {}).get("worst_kind")))
    contract.save(out / "catalog.json", dict(
        conventions=wc.conventions(), cases=cases,
        clips=[{k: d[k] for k in ("id", "case", "clip", "regime", "title", "description", "styles", "window",
                                  "timeline_start", "frames", "loop_range", "blender")} for d in docs],
        clearance=clearance))
    (out / "CATALOG.md").write_text(markdown(docs, clearance))
    print(json.dumps(dict(clips=len(docs), catalog=str(out / "catalog.json"))))
